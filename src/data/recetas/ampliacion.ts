import type { Receta } from "@/types/receta";
import { IMG, ing, paso } from "./_helpers";

type Datos = Omit<Receta, "ingredientes" | "pasos" | "imagenes"> & {
  ingredientes: Array<[string, string, number, Parameters<typeof ing>[3], string?]>;
  elaboracion: [string, string, string, string];
};

function receta(datos: Datos): Receta {
  const { ingredientes, elaboracion, ...base } = datos;
  return {
    ...base,
    ingredientes: ingredientes.map(([id, nombre, cantidad, unidad, notas]) =>
      ing(id, nombre, cantidad, unidad, notas),
    ),
    pasos: [
      paso(1, "Preparar", elaboracion[0]),
      paso(2, "Cocinar la base", elaboracion[1]),
      paso(
        3,
        "Terminar la cocción",
        elaboracion[2],
        base.tiempoCoccion > 0
          ? { tiempoSegundos: Math.min(base.tiempoCoccion, 45) * 60 }
          : undefined,
      ),
      paso(4, "Servir", elaboracion[3]),
    ],
    imagenes: [IMG],
  };
}

